#!/usr/bin/env python3
"""Actual pinned AFlow SDK, native formatter/evaluator and constructor fixtures."""
from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
from types import SimpleNamespace
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
from arena.frameworks.drivers import aflow_gateway_pilot as pilot
from arena.frameworks.drivers._gsm8k_pilot import write_json, load_dataset


def check(source, dataset_path, output):
    from arena.frameworks.runtime import verify_source
    revision = verify_source(source, pilot.COMMIT)
    pilot.verify_source(source)
    dataset = load_dataset(dataset_path)
    if not output.is_absolute() or output.exists():
        raise ValueError("Use a new absolute fixture directory")
    output.mkdir(parents=True, mode=0o750)
    workspace = output / "fixture-source"
    shutil.copytree(source, workspace, ignore=shutil.ignore_patterns(".git", "__pycache__", "*.pyc"))
    os.chdir(workspace)
    sys.path.insert(0, str(workspace))

    def deny_network(event, args):
        if event in {"socket.connect", "socket.sendto"}:
            raise RuntimeError("Network forbidden in AFlow fixture")
    sys.addaudithook(deny_network)
    import openai
    from openai import _base_client
    httpx = getattr(_base_client, "httpx", None) or _base_client.httpx2
    from scripts.formatter import XmlFormatter
    from scripts.optimizer import GraphOptimize
    from benchmarks.gsm8k import GSM8KBenchmark
    from benchmarks.benchmark import BaseBenchmark
    import scripts.async_llm as native_llm
    from workspace.GSM8K.workflows.round_1.graph import Workflow
    from workspace.GSM8K.workflows.template.operator import ScEnsemble, Programmer

    calls, records = [], []
    text = ["Fixture answer:2"]
    cycle = {"active": False, "proposal_count": 0, "events": []}
    # Known, reviewed inert graph code. No text generated by a model is executed
    # by this fixture. Native GraphUtils still writes and imports both rounds.
    fixture_graph = '''class Workflow:
    def __init__(self, name, llm_config, dataset):
        self.name, self.dataset = name, dataset
        self.llm = create_llm_instance(llm_config)
        self.custom = operator.Custom(self.llm)

    async def __call__(self, problem):
        solution = await self.custom(input=problem, instruction=prompt_custom.FIXTURE_INSTRUCTION)
        return solution["response"], self.llm.get_usage_summary()["total_cost"]
'''
    fixture_metric = GSM8KBenchmark("GSM8K", "unused", str(output))
    gold = {row["question"]: fixture_metric.extract_number(row["answer"])
            for split in ("validation", "heldout") for row in dataset["selected_records"][split]}
    heldout_questions = {row["question"] for row in dataset["selected_records"]["heldout"]}

    def full_cycle_response(body):
        prompt = body["messages"][-1]["content"]
        assert body["model"] == pilot.MODELS[0]
        if "<graph>graph</graph>" in prompt:
            assert not Path("data/datasets/gsm8k_test.jsonl").exists()
            assert not any(question in prompt for question in heldout_questions)
            cycle["proposal_count"] += 1
            number = cycle["proposal_count"]
            assert number in (1, 2)
            variant = "A" if number == 1 else "B"
            cycle["events"].append({"kind": "native_proposal", "round": number + 1})
            return (f"<modification>Fixed inert variant {variant}</modification><graph>{fixture_graph}</graph>"
                    f"<prompt>FIXTURE_INSTRUCTION = 'Fixture variant {variant}. '</prompt>")
        question = next((q for q in gold if prompt == q or prompt in
                         ("Fixture variant A. " + q, "Fixture variant B. " + q)), None)
        assert question is not None, "Unexpected fixture execution prompt"
        heldout = question in heldout_questions
        if heldout:
            assert cycle["proposal_count"] == 2
            frozen = json.loads((output / "full-cycle" / "selection.json").read_text())
            assert frozen["round"] == 2 and frozen["heldout_seen"] is False
            if cycle.get("frozen_selection") is None:
                cycle["frozen_selection"] = hashlib.sha256((output / "full-cycle" / "selection.json").read_bytes()).hexdigest()
            assert cycle["frozen_selection"] == hashlib.sha256((output / "full-cycle" / "selection.json").read_bytes()).hexdigest()
        else:
            assert not Path("data/datasets/gsm8k_test.jsonl").exists()
        correct = prompt.startswith("Fixture variant A. ")
        cycle["events"].append({"kind": "heldout" if heldout else "validation", "variant": "A" if correct else "seed-or-B"})
        # Deliberately predetermined mock scores, never research/model results.
        return "Fixed fixture answer: " + str(gold[question] if correct else gold[question] + 1)

    def respond(request):
        body = json.loads(request.content)
        assert str(request.url) == pilot.ENDPOINT + "/chat/completions"
        assert request.headers["authorization"] == "Bearer inert-aflow-fixture"
        assert body["model"] in pilot.MODELS
        assert set(body) == {"model", "messages", "temperature", "top_p"}
        calls.append(body)
        content = full_cycle_response(body) if cycle["active"] else text[0]
        return httpx.Response(200, json={"id": "fixture-" + str(len(calls)), "object": "chat.completion",
            "created": 1, "model": body["model"],
            "choices": [{"index": 0, "message": {"role": "assistant", "content": content}, "finish_reason": "stop"}],
            "usage": {"prompt_tokens": 2, "completion_tokens": 3, "total_tokens": 5}})
    real_sdk = openai.AsyncOpenAI
    def sdk_factory(**kwargs):
        assert kwargs["max_retries"] == 0 and kwargs["timeout"] == 330
        return real_sdk(**kwargs, http_client=httpx.AsyncClient(transport=httpx.MockTransport(respond)))

    original_sdk, original_evaluate = native_llm.AsyncOpenAI, BaseBenchmark.evaluate_all_problems
    for model in pilot.MODELS:
        budget = pilot.GatewayBudget(model, output / (model + ".usage.json"), sdk_factory=sdk_factory)
        before = len(calls)
        with pilot.configure_native(budget):
            optimizer = pilot.build_native(model, "inert-aflow-fixture")
            assert optimizer.max_rounds == 2 and optimizer.validation_rounds == 1
            assert optimizer.operators == ["Custom", "ScEnsemble", "Programmer"]
            assert optimizer.optimize_llm_config.model == optimizer.execute_llm_config.model == model
            async def exercise():
                text[0] = "Fixture answer:2"
                graph = Workflow("GSM8K", optimizer.execute_llm_config, "GSM8K")
                native = GSM8KBenchmark("GSM8K", "unused", str(output))
                result = await native.evaluate_problem({"question": "Fixed fixture: one plus one?", "answer": "#### 2"}, graph)
                assert result[3] == 1.0
                # Establish the native scoring semantics, without replacing them.
                assert native.extract_number("#### 2 then 3") == 3.0
                assert native.calculate_score(2, 2.0000001)[0] == 1.0
                assert native.calculate_score(2, 3)[0] == 0.0
                text[0] = "<modification>Fixture edit</modification><graph>class Workflow: pass</graph><prompt>FIXTURE = 'x'</prompt>"
                parsed = await optimizer.optimize_llm.call_with_format("Fixed parser fixture", XmlFormatter.from_model(GraphOptimize))
                assert parsed["modification"] == "Fixture edit" and parsed["graph"] == "class Workflow: pass"
                text[0] = "<solution_letter>B</solution_letter>"
                assert await ScEnsemble(graph.llm)(["first", "second"], "fixture") == {"response": "second"}
                text[0] = "```python\ndef solve():\n    return 2\n```"
                code = await Programmer(graph.llm).code_generate("fixture", "none", "none", "code_fill")
                assert "def solve" in code["response"]  # Native key, parse only; no execution.
                text[0] = "Invalid structured fixture"
                # At this pin GraphOptimize fields default to empty strings;
                # XmlFormatter therefore accepts missing tags as {}. Preserve
                # this real native behavior, rather than invent strict JSON.
                assert await optimizer.optimize_llm.call_with_format(
                    "Fixed malformed fixture", XmlFormatter.from_model(GraphOptimize)) == {}
            asyncio.run(exercise())
            # A different native round creates a new event loop; transport must
            # remain usable without reusing a closed-loop connection pool.
            text[0] = "Cross-loop fixture"
            assert asyncio.run(optimizer.optimize_llm("Cross-loop fixture")) == text[0]
            records.append({"model": model, "mock_sdk_requests": len(calls) - before,
                "both_roles_exact": True, "native_text_xml_code_formats": True})
        assert native_llm.AsyncOpenAI is original_sdk and BaseBenchmark.evaluate_all_problems is original_evaluate

    # Invoke the actual native round with a pre-exhausted transport. It must
    # escape both benchmark and optimizer Exception retry handlers with no SDK call.
    pilot.materialize_data(dataset, "validation")
    assert not Path("data/datasets/gsm8k_test.jsonl").exists()
    exhausted = pilot.GatewayBudget(pilot.MODELS[0], sdk_factory=sdk_factory, limit=1)
    exhausted.records.append({"status": "fixture-preexhausted"})
    before = len(calls)
    with pilot.configure_native(exhausted):
        optimizer = pilot.build_native(pilot.MODELS[0], "inert-aflow-fixture")
        try:
            optimizer.optimize("Graph")
        except pilot.PilotBudgetExhausted:
            pass
        else:
            raise AssertionError("Native loop swallowed the budget stop")
    assert len(calls) == before
    assert not Path("data/datasets/gsm8k_test.jsonl").exists()
    # Clear only the validation input created by the preceding abort fixture;
    # the native source copy remains a seed-only workspace with empty history.
    Path("data/datasets/gsm8k_validate.jsonl").unlink()
    cycle["active"] = True
    before = len(calls)
    os.environ["OPENAI_API_KEY"] = "inert-aflow-fixture"
    with patch.object(openai, "AsyncOpenAI", sdk_factory):
        returncode = pilot.run(SimpleNamespace(model=pilot.MODELS[0], dataset=dataset_path,
                                               output=output / "full-cycle"))
    assert returncode == 0
    receipt = json.loads((output / "full-cycle/pilot.json").read_text())
    assert receipt["status"] == "completed" and receipt["native_completed"] and receipt["heldout_completed"]
    native_results = json.loads(Path("workspace/GSM8K/workflows/results.json").read_text())
    assert [(r["round"], r["score"]) for r in native_results] == [(1, 0.0), (2, 1.0), (3, 0.0)]
    assert receipt["selected_round"] == 2 and set(receipt["heldout"]) == {"1", "2"}
    assert receipt["heldout"]["1"]["score"] == 0.0 and receipt["heldout"]["2"]["score"] == 1.0
    assert cycle["proposal_count"] == 2
    assert sum(e["kind"] == "validation" for e in cycle["events"]) == 24
    assert sum(e["kind"] == "heldout" for e in cycle["events"]) == 16
    assert len(calls) - before == 42
    usage = json.loads((output / "full-cycle/usage.json").read_text())
    assert usage["problem_evaluations_admitted"] == 40 and usage["requests_attempted"] == 42
    full_proof = {"model": pilot.MODELS[0], "native_rounds": [1, 2, 3], "selected_round": 2,
        "selection_fixed_before_heldout": True, "mock_sdk_requests": len(calls) - before,
        "validation_problem_evaluations": 24, "heldout_problem_evaluations": 16,
        "fixture_graph_sha256": hashlib.sha256(fixture_graph.encode()).hexdigest(),
        "selection_sha256": cycle["frozen_selection"], "events": cycle["events"],
        "completed_receipt_sha256": hashlib.sha256((output / "full-cycle/pilot.json").read_bytes()).hexdigest(),
        "model_generated_code_executed": False, "scientific_result": False}
    write_json(output / "full-cycle-proof.json", full_proof)
    proof = {"schema": "arena.aflow-gateway-conformance/1", "source": revision,
        "dataset_sha256": pilot.DATASET_SHA256, "records": records,
        "integration_sha256": {
            "driver": hashlib.sha256(Path(pilot.__file__).read_bytes()).hexdigest(),
            "fixture": hashlib.sha256(Path(__file__).read_bytes()).hexdigest()},
        "network": "denied", "model_calls": 0, "model_generated_candidate_executions": 0,
        "native_fixture_search_completed": True, "sdk_timeout_seconds": 330,
        "full_native_cycle": full_proof, "budget_escaped_native_retries": True,
        "heldout_not_materialized_before_search": True,
        "scope": "Actual native two-round search/evaluation/selection/heldout with predetermined inert graph and mock responses, plus seven-model SDK fixtures. No scientific result or live integration claim."}
    write_json(output / "conformance.json", proof)
    return proof


def main():
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(check(args.source, args.dataset, args.output), indent=2))


if __name__ == "__main__":
    main()
