"""Simple Assembly Line Balancing (DGA2D).

Protocol: recreated. Candidate contract: priority(instance) -> one score per task (instance has times, predecessors, cycle_time); stations are filled with the highest-priority eligible task that fits. Score: mean number of stations.
Generated by scripts/build_suite.py from the family "salbp" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_tasks': 30, 'seed': 0}


def task(module):
    instances = combinatorial.salbp_instances(P['n_instances'], P['n_tasks'], P['seed'])
    value = combinatorial.salbp_score(module.priority, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
