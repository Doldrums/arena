"""CVRP ACO (ReEvo, MCTS-AHD).

Protocol: recreated. Candidate contract: heuristics(distance_matrix, coordinates, demands, capacity) -> matrix of edge attractiveness. Score: mean best CVRP cost found by ant colony optimization.
Generated by scripts/build_suite.py from the family "cvrp_aco" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 300
P = {'n_instances': 3, 'n_customers': 50, 'capacity': 50, 'n_ants': 20, 'n_iterations': 30, 'seed': 0}


def task(module):
    instances = combinatorial.cvrp_instances(P['n_instances'], P['n_customers'], P['seed'], capacity=P['capacity'])
    value = combinatorial.cvrp_aco_score(module.heuristics, instances, n_ants=P['n_ants'], n_iterations=P['n_iterations'])
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
