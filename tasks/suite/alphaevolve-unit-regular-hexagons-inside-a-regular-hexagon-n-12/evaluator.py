from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import geometry  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n': 12, 'published': 3.9419123}


def task(module):
    inner, center, side, angle = module.construct()
    value = geometry.hexagon_packing_outer_side(inner, center, side, angle, P['n'])
    return runtime.success(value, 'minimize', published=P.get('published'))


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
