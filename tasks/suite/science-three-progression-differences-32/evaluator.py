"""Thirty-two integers with many distinct 3-term progression differences (Problem-bank constructions: number theory and additive sets supplement).

Protocol: recreated_verified. Candidate contract: construct() -> exactly 32 distinct integers in 1..512. The score is the number of distinct d > 0 such that a, a + d, a + 2d all lie in the set for some a. Maximize..
Generated by scripts/build_suite.py from the family "science_prize_h_ap_differences" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_h  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 120
P = {'size': 32, 'bound': 512}


def task(module):
    value, details = science_prize_h.three_progression_differences(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
