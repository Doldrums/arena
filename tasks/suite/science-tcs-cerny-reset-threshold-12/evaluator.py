"""Černý problem: 12-state binary automata with long reset thresholds (Prize-listed mathematical problems supplement).

Protocol: recreated_verified. Candidate contract: construct() -> two length-N lists of destination states in 0..N-1, defining a complete binary deterministic automaton. It must synchronize. Score is its EXACT shortest reset-word length, maximized. The evaluator exhaustively searches the subset automaton and reports a shortest word. Fixed N=12 is a local finite restriction, not a proof of Černý's general conjecture..
Generated by scripts/build_suite.py from the family "science_prize_cerny" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 60
P = {'n': 12}


def task(module):
    value, details = science_prize.reset_threshold(module.construct(), P['n'])
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
