"""Flexible Job-Shop Scheduling (DGA2D, A2DEPT).

Protocol: recreated. Candidate contract: dispatch(ready_operations, time) -> index of the ready operation to start (optionally (index, machine)); each ready operation is a dict with job, op, machine_options {machine: duration}, remaining_ops, remaining_work. Score: mean makespan.
Generated by scripts/build_suite.py from the family "job_shop" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_jobs': 10, 'n_machines': 5, 'flexible': True, 'open_shop': False, 'seed': 0}


def task(module):
    instances = combinatorial.job_shop_instances(P['n_instances'], P['n_jobs'], P['n_machines'], P['seed'], flexible=P['flexible'], open_shop=P['open_shop'])
    value = combinatorial.job_shop_score(module.dispatch, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
