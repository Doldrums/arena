"""Procedurally generated symbolic equations (LaSR).

Protocol: recreated. Candidate contract: fit(X_train: np.ndarray[n, d], y_train) -> predict(X) callable; the candidate is a symbolic-regression algorithm run on every equation of the set. Score: mean held-out NMSE over the equations.
Generated by scripts/build_suite.py from the family "sr_algorithm" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import regression  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 300
P = {'targets': ['random_univariate', 'polynomial_cubic', 'kan_rescue_univariate', 'special_functions'], 'seed': 0}


def task(module):
    import numpy as np
    names = P['targets']
    scores = []
    for name in names:
        spec = regression.FEYNMAN.get(name) or regression.UNIVARIATE[name]
        x_tr, y_tr = regression.synthetic_data(spec, 200, P['seed'])
        x_te, y_te = regression.synthetic_data(spec, 200, P['seed'] + 1)
        predict = module.fit(np.column_stack(x_tr), y_tr)
        pred = np.asarray(predict(np.column_stack(x_te)), dtype=float).ravel()
        runtime.require(pred.shape == y_te.shape and np.all(np.isfinite(pred)), f'predict must return a finite prediction per sample ({name})')
        scores.append(float(np.mean((pred - y_te) ** 2) / (np.var(y_te) + 1e-12)))
    return runtime.success(float(np.mean(scores)), 'minimize', per_equation=dict(zip(names, scores)))


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
