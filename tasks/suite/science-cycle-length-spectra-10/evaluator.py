"""Realizing every set of cycle lengths on 10 vertices (Problem-bank constructions: hypergraphs, graph constructions and instance-solving methods supplement).

Protocol: recreated_verified. Candidate contract: construct() -> a list of at most 500 simple graphs on vertices 0..9, each a list of edges [u, v]. The cycle set of a graph (the lengths of its cycles, computed exactly by dynamic programming over paths) is recorded for every graph. Maximize the number of distinct cycle sets; the optimum is 133..
Generated by scripts/build_suite.py from the family "science_prize_i_cycle_spectra" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_i  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 120
P = {'n': 10, 'max_graphs': 500}


def task(module):
    value, details = science_prize_i.cycle_spectra(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
