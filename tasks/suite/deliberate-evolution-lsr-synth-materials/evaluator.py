"""LSR-Synth Materials (Deliberate Evolution).

Protocol: recreated. Candidate contract: equation(X: np.ndarray[n, d], params: np.ndarray[10]) -> np.ndarray[n]; columns of X follow the instance's input_vars; parameters are fitted by BFGS on the train split. Score: mean NMSE on the test split over the selected LLM-SRBench instances.
Generated by scripts/build_suite.py from the family "lsr_equation" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import regression  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 900
P = {'subset': 'lsr_synth_matsci', 'instance_id': None, 'max_instances': 4, 'seed': 0}


def task(module):
    out = regression.lsr_score(module.equation, P['subset'], P.get('instance_id'), max_instances=P.get('max_instances', 4), seed=P.get('seed', 0))
    return runtime.success(out['score'], 'minimize', per_instance=out['per_instance'], instances=out['instances'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
