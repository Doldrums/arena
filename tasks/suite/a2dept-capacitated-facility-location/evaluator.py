"""Capacitated Facility Location (A2DEPT, FunL2O).

Protocol: recreated. Candidate contract: assign(demands, capacities, open_cost, assign_cost[customer, facility]) -> facility index per customer respecting capacities. Score: mean total opening + assignment cost.
Generated by scripts/build_suite.py from the family "facility_location" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_facilities': 20, 'n_customers': 100, 'seed': 0}


def task(module):
    instances = combinatorial.facility_location_instances(P['n_instances'], P['n_facilities'], P['n_customers'], P['seed'])
    value = combinatorial.facility_location_score(module.assign, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
