"""Integers up to 10^18 with many representations as sums of two powerful numbers (Problem-bank constructions: hypergraphs, graph constructions and instance-solving methods supplement).

Protocol: recreated_verified. Candidate contract: construct() -> {'N': N, 'pairs': [[a, b], ...]} with 2 <= N <= 10^18 and distinct pairs a <= b, a + b = N, where a and b are powerful (every prime factor appears squared; 1 counts as powerful), checked by exact factorization. The score is the number of pairs, a certified lower bound on the representation count. Maximize..
Generated by scripts/build_suite.py from the family "science_prize_i_powerful_pairs" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_i  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 120
P = {'bound': 1000000000000000000}


def task(module):
    value, details = science_prize_i.powerful_pairs(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
