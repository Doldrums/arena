"""Dense graphs on 20 vertices edge-coloured with 20 colours so every 4-cycle is rainbow (Problem-bank constructions: hypergraphs, graph constructions and instance-solving methods supplement).

Protocol: recreated_verified. Candidate contract: construct() -> coloured edges [[u, v, c], ...] of a simple graph on vertices 0..19 with colours 0..19. Every 4-cycle (as a subgraph) must receive four distinct colours, checked over all 4-cycles. Maximize the number of edges..
Generated by scripts/build_suite.py from the family "science_prize_i_rainbow_c4" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_i  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 120
P = {'n': 20, 'colours': 20}


def task(module):
    value, details = science_prize_i.rainbow_c4(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
