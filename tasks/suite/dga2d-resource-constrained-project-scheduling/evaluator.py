from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_activities': 30, 'n_resources': 4, 'seed': 0}


def task(module):
    instances = combinatorial.rcpsp_instances(P['n_instances'], P['n_activities'], P['n_resources'], P['seed'])
    value = combinatorial.rcpsp_score(module.priority, instances)
    return runtime.success(value, 'minimize')


