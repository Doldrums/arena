"""Path decompositions of three fixed connected graphs (Gallai's conjecture) (Problem-bank constructions: extremal graphs, hypergraphs and designs supplement).

Protocol: recreated_verified. Candidate contract: construct() -> three lists of paths (vertex lists), one per fixed instance graph generated by instance_graph(n, p, seed) for (20,0.3,1), (25,0.3,2), (30,0.25,3) in the verifier. Paths must be simple, use graph edges, be edge-disjoint and cover all edges. Minimize the total number of paths; Gallai's conjecture predicts at most 10+13+15 = 38..
Generated by scripts/build_suite.py from the family "science_prize_f_gallai_paths" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_f  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {}


def task(module):
    value, details = science_prize_f.gallai_paths(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
