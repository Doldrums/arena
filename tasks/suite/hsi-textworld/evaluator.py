"""TextWorld (HSI).

Protocol: recreated. Candidate contract: act(observation, valid_actions, history, llm) -> str: the next text command. observation is the game text after the last command, valid_actions the parser-accepted commands for the current state, history the list of (action, observation, reward) so far, llm the cached budgeted OpenRouter client (llm(prompt, system=None, max_tokens=None) -> str). Score: final game score / maximum score after STEPS commands, averaged over RUNS seeded plays. Higher is better..
Generated by scripts/build_suite.py from the family "text_game" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import text_game  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'game': 'treasure_hunter', 'engine': 'textworld', 'steps': 40, 'runs': 1}


def task(module):
    value, details = text_game.text_game_score(module.act, P['game'], P['engine'], steps=P.get('steps', 40), runs=P.get('runs', 1))
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
