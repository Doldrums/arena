"""Multiple knapsack ACO (ReEvo, MCTS-AHD, RedAHD).

Protocol: recreated. Candidate contract: heuristics(prizes, weights) -> one attractiveness score per item (weights has shape (constraints, items)). Score: mean best total prize.
Generated by scripts/build_suite.py from the family "mkp_aco" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 300
P = {'n_instances': 3, 'n_items': 100, 'n_constraints': 5, 'n_ants': 20, 'n_iterations': 30, 'seed': 0}


def task(module):
    instances = combinatorial.mkp_instances(P['n_instances'], P['n_items'], P['n_constraints'], P['seed'])
    value = combinatorial.mkp_aco_score(module.heuristics, instances, n_ants=P['n_ants'], n_iterations=P['n_iterations'])
    return runtime.success(value, 'maximize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
