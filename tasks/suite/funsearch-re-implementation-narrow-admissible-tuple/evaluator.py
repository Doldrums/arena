"""Narrow admissible tuple (FunSearch re-implementation, MCTS-AHD).

Protocol: recreated. Candidate contract: construct() -> list of distinct integers in [0, n] forming an admissible tuple: for every prime p <= len(tuple) some residue class mod p is missed (FunSearch fixed-diameter formulation). Score: tuple size.
Generated by scripts/build_suite.py from the family "admissible_tuple" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 300
P = {'n': 5000}


def task(module):
    value = combinatorial.admissible_tuple_size(module.construct(), P['n'])
    return runtime.success(value, 'maximize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
