"""Traveling salesman GLS (EoH, CodeEvolve, HSEvo, LLaMEA-HPO, MCTS-AHD, ReEvo).

Protocol: recreated. Candidate contract: update_edge_distance(edge_distance, local_opt_tour, edge_n_used) -> np.ndarray: perturbed distance matrix that guides the next 2-opt pass (EoH tsp_gls contract). Score: mean best tour length.
Generated by scripts/build_suite.py from the family "tsp_gls" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 300
P = {'n_instances': 3, 'n_nodes': 100, 'iterations': 20, 'seed': 0}


def task(module):
    instances = combinatorial.euclidean_instances(P['n_instances'], P['n_nodes'], P['seed'])
    value = combinatorial.tsp_gls_score(module.update_edge_distance, instances, iterations=P['iterations'])
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
