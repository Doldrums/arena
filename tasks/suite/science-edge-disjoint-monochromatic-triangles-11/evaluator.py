"""Two-colourings of K11 with few edge-disjoint monochromatic triangles (Problem-bank constructions: Ramsey theory and colourings supplement).

Protocol: recreated_verified. Candidate contract: construct() -> {'n': 11, 'colors': [...]}: colour 0 or 1 for each of the 55 pairs (i,j), i<j, in lexicographic order. The score is the maximum number of edge-disjoint monochromatic triangles, computed exactly per colour by branch and bound. Minimize; the known optimum is 6..
Generated by scripts/build_suite.py from the family "science_prize_e_monochromatic_triangle_packing" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_e  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n': 11}


def task(module):
    value, details = science_prize_e.monochromatic_triangle_packing(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
