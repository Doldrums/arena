"""Permutations avoiding long monotone progressions (Problem-bank constructions: additive combinatorics supplement).

Protocol: recreated_verified. Candidate contract: construct() -> a permutation of 1..n=128. Minimize the longest subsequence whose values form an increasing OR decreasing nonconstant arithmetic progression; subsequence positions need not be adjacent. A known finite construction attains 2, so this is a rediscovery task..
Generated by scripts/build_suite.py from the family "science_prize_a_permutation_progression" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_a  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 60
P = {'n': 128}


def task(module):
    value, details = science_prize_a.permutation_progression(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
