"""Low discrepancy on all arithmetic progressions (Problem-bank constructions: additive combinatorics supplement).

Protocol: recreated_verified. Candidate contract: construct() -> exactly n=256 Python integer signs -1 or +1. Minimize the maximum absolute signed sum on ANY arithmetic progression contained in [1,256], any start, positive step and length including one..
Generated by scripts/build_suite.py from the family "science_prize_a_progression_discrepancy" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_a  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 60
P = {'n': 256}


def task(module):
    value, details = science_prize_a.progression_discrepancy(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
