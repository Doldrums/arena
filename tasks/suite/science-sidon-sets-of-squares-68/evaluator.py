"""Largest Sidon set among the first 68 squares (Problem-bank constructions: number theory and additive sets supplement).

Protocol: recreated_verified. Candidate contract: construct() -> distinct bases x in 1..68 whose squares form a Sidon set: all sums x^2 + y^2 with x <= y are distinct. Maximize the number of bases; the optimum is 32..
Generated by scripts/build_suite.py from the family "science_prize_h_sidon_squares" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_h  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 120
P = {'m': 68}


def task(module):
    value, details = science_prize_h.sidon_squares(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
