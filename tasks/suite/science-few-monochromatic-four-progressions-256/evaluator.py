"""Two-colourings of [1,256] with few monochromatic four-term progressions (Problem-bank constructions: Ramsey theory and colourings supplement).

Protocol: recreated_verified. Candidate contract: construct() -> 256 colours in {0,1} for the integers 1..256. Minimize the exact number of monochromatic 4-term arithmetic progressions a, a+d, a+2d, a+3d with d >= 1 inside 1..256..
Generated by scripts/build_suite.py from the family "science_prize_e_monochromatic_progressions" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_e  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n': 256, 'length': 4}


def task(module):
    value, details = science_prize_e.monochromatic_progressions(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
