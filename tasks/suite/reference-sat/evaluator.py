"""Satisfiable 3-CNF solving (SATLUTION).

Protocol: recreated. Candidate contract: solve(instance) -> list of booleans (instance has n and clauses as signed 1-based literals). Score: fraction of satisfiable instances solved.
Generated by scripts/build_suite.py from the family "sat_solver" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 300
P = {'n_instances': 10, 'n_vars': 50, 'seed': 0}


def task(module):
    instances = combinatorial.sat_instances(P['n_instances'], P['n_vars'], P['seed'])
    value = combinatorial.sat_score(module.solve, instances)
    return runtime.success(value, 'maximize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
