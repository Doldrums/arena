"""Permutation flow shop scheduling (EoH, CodeEvolve, DGA2D, A2DEPT).

Protocol: recreated. Candidate contract: order_jobs(processing_times: np.ndarray[jobs, machines]) -> permutation of job indices. Score: mean makespan.
Generated by scripts/build_suite.py from the family "flow_shop" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_jobs': 50, 'n_machines': 10, 'seed': 0}


def task(module):
    instances = combinatorial.flow_shop_instances(P['n_instances'], P['n_jobs'], P['n_machines'], P['seed'])
    value = combinatorial.flow_shop_score(module.order_jobs, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
