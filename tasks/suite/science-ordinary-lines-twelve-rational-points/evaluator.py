"""Twelve rational points with few ordinary lines (Problem-bank constructions: discrete geometry and analysis supplement).

Protocol: recreated_verified. Candidate contract: construct() -> exactly 12 distinct integer points [x, y] with |x|, |y| <= 10^9, not all collinear. Minimize the number of lines containing exactly two of the points (exact)..
Generated by scripts/build_suite.py from the family "science_prize_g_ordinary_lines" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_g  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n': 12, 'bound': 1000000000}


def task(module):
    value, details = science_prize_g.ordinary_lines(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
