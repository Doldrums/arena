"""Capacitated vehicle routing (RedAHD, A2DEPT, CAE, DGA2D, EoH-S, ReEvo).

Protocol: recreated. Candidate contract: select_next_node(current_node, depot, unvisited_nodes, rest_capacity, demands, distance_matrix) -> int; return 0 (depot) to close a route. Score: mean total route length.
Generated by scripts/build_suite.py from the family "cvrp_constructive" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 8, 'n_customers': 50, 'capacity': 50, 'seed': 0}


def task(module):
    instances = combinatorial.cvrp_instances(P['n_instances'], P['n_customers'], P['seed'], capacity=P['capacity'])
    value = combinatorial.cvrp_constructive_score(module.select_next_node, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
