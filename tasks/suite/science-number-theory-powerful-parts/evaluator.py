"""Large powerful-part product for consecutive integers (Problem-bank constructions: arithmetic and extremal sets supplement).

Protocol: recreated_verified. Candidate contract: construct() -> candidate. Return an integer n in [10000,1000000]. Its powerful part is the product of FULL prime powers p^e with exponent e>=2 in its factorization. Maximize powerful_part(n)*powerful_part(n+1)..
Generated by scripts/build_suite.py from the family "science_prize_b_powerful_parts" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_b  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 60
P = {'lower': 10000, 'upper': 1000000}


def task(module):
    value, details = science_prize_b.powerful_parts(module.construct(), **P)
    return runtime.success(value, 'maximize', lean_verified=False, **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
