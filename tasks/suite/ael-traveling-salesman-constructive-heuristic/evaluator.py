"""Traveling salesman constructive heuristic (AEL, CAE, DGA2D, EoH-S, MCTS-AHD, MEoH, RedAHD, ReEvo, EoH).

Protocol: recreated. Candidate contract: select_next_node(current_node, destination_node, unvisited_nodes: np.ndarray, distance_matrix: np.ndarray) -> int (EoH/LLM4AD contract). Score: mean tour length over generated Euclidean instances.
Generated by scripts/build_suite.py from the family "tsp_constructive" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 8, 'n_nodes': 50, 'seed': 0}


def task(module):
    instances = combinatorial.euclidean_instances(P['n_instances'], P['n_nodes'], P['seed'])
    value = combinatorial.tsp_constructive_score(module.select_next_node, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
