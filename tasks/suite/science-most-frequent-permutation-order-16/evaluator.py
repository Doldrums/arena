"""Most frequent element order in the symmetric group S16 (Problem-bank constructions: geometry and discrete structures supplement).

Protocol: recreated_verified. Candidate contract: construct() -> an attainable permutation order k in S16. Maximize the exact number of permutations of that order. All integer partitions of 16 are enumerated and their cycle-type multiplicities 16! / product(i**m_i * m_i!) are summed by cycle-length lcm..
Generated by scripts/build_suite.py from the family "science_prize_d_frequent_permutation_order" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_d  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 60
P = {'n': 16}


def task(module):
    value, details = science_prize_d.frequent_permutation_order(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
