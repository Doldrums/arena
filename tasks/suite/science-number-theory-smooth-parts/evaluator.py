"""Few distinct small-prime parts in a short integer interval (Problem-bank constructions: arithmetic and extremal sets supplement).

Protocol: recreated_verified. Candidate contract: construct() -> candidate. Return n in [1000,1000000]. For each n+i,1<=i<=24, extract its complete factor composed of primes STRICTLY BELOW 24. MINIMIZE the number of distinct extracted factors..
Generated by scripts/build_suite.py from the family "science_prize_b_smooth_parts" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_b  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 60
P = {'lower': 1000, 'upper': 1000000, 'length': 24}


def task(module):
    value, details = science_prize_b.smooth_parts(module.construct(), **P)
    return runtime.success(value, 'minimize', lean_verified=False, **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
