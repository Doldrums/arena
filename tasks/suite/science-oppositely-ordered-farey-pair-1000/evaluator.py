"""Nearby oppositely ordered fractions in the Farey sequence (Problem-bank constructions: geometry and discrete structures supplement).

Protocol: recreated_verified. Candidate contract: construct() -> [[a,b],[c,d]], two reduced fractions in [0,1] with denominators <=1000, a/b<c/d, and (c-a)*(d-b)<0. Minimize their rank difference in the complete Farey sequence of order 1000, including 0/1 and 1/1. Every rank is recomputed exactly..
Generated by scripts/build_suite.py from the family "science_prize_d_opposite_farey_pair" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_d  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 60
P = {'order': 1000}


def task(module):
    value, details = science_prize_d.opposite_farey_pair(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
