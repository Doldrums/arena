"""Capacitated Electric Vehicle Routing with Time Windows (A2DEPT).

Protocol: recreated. Candidate contract: plan(instance) -> list of routes (lists of node ids; depot 0 implicit; charging stations may appear repeatedly). Vehicles have capacity, battery (1 unit per distance) and must respect customer time windows. Score: mean total distance.
Generated by scripts/build_suite.py from the family "evrptw" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 3, 'n_customers': 25, 'n_stations': 4, 'seed': 0}


def task(module):
    instances = combinatorial.evrptw_instances(P['n_instances'], P['n_customers'], P['n_stations'], P['seed'])
    value = combinatorial.evrptw_score(module.plan, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
