"""Singular Plural (Promptbreeder, PhaseEvo).

Protocol: recreated. Candidate contract: solve(question, llm) -> answer string; llm(prompt_or_messages, system=None, max_tokens=None) is a budgeted, cached OpenRouter client. Score: mean per-item accuracy (or F1) on a fixed seeded sample of the benchmark.
Generated by scripts/build_suite.py from the family "llm_benchmark" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import llm  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 900
P = {'benchmark': 'instruction_induction', 'benchmark_options': {'task': 'singular_to_plural'}, 'seed': 0}


def task(module):
    from autoresearch_suite import llm_benchmarks
    spec = llm_benchmarks.spec(P['benchmark'], **P.get('benchmark_options', {}))
    out = llm.benchmark_score(module.solve, spec, seed=P.get('seed', 0))
    return runtime.success(out['score'], 'maximize', items=out['items'], crashes=out['crashes'], usage=out['usage'], benchmark=P['benchmark'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
