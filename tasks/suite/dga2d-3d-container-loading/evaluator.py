"""3D Container Loading (DGA2D).

Protocol: recreated. Candidate contract: load(boxes, container) -> one placement (bin, x, y, z, w, h, d) per box with bin 0 for loaded boxes and -1 for boxes left out. Score: mean fraction of container volume filled.
Generated by scripts/build_suite.py from the family "container_loading" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_boxes': 60, 'seed': 0}


def task(module):
    instances = combinatorial.box_instances(P['n_instances'], P['n_boxes'], P['seed'])
    value = combinatorial.container_loading_score(module.load, instances)
    return runtime.success(value, 'maximize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
