"""Online bin packing (EoH, CodeEvolve, EoH-S, HSEvo, LLaMEA-HPO, MCTS-AHD, MEoH, RedAHD).

Protocol: recreated. Candidate contract: priority(item: float, bins: np.ndarray) -> np.ndarray of one score per bin with enough remaining capacity; the item goes to the highest-scoring bin (FunSearch/EoH contract). Score: mean excess over the L1 lower bound in percent.
Generated by scripts/build_suite.py from the family "online_bin_packing" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import combinatorial  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'n_instances': 5, 'n_items': 1000, 'capacity': 100, 'seed': 0}


def task(module):
    instances = combinatorial.weibull_bin_packing_instances(P['n_instances'], P['n_items'], P['capacity'], seed=P['seed'])
    value = combinatorial.online_bin_packing_score(module.priority, instances)
    return runtime.success(value, 'minimize')


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
