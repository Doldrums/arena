"""Large gaps between sums of two squares (Problem-bank constructions: additive combinatorics supplement).

Protocol: recreated_verified. Candidate contract: construct() -> [a,b], positive endpoints a<b<=maximum=10000000, b-a<=10000, both sums of two integer squares (zero is permitted). No interior integer may be a sum of two squares. Maximize b-a..
Generated by scripts/build_suite.py from the family "science_prize_a_two_square_gap" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_a  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 60
P = {'maximum': 10000000, 'maximum_gap': 10000}


def task(module):
    value, details = science_prize_a.two_square_gap(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
