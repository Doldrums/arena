"""Divisibility-antichain representations by smooth numbers (Problem-bank constructions: additive combinatorics supplement).

Protocol: recreated_verified. Candidate contract: construct() -> 128 rows corresponding to targets 1..128. Every row must contain 1..30 distinct positive 2^a*3^b*5^c terms summing to its target; no chosen term may divide another. All targets require valid representations. Minimize the total number of summands over all targets, an explicit local refinement of finite d-completeness..
Generated by scripts/build_suite.py from the family "science_prize_a_antichain_representations" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_a  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 60
P = {'maximum_terms': 30}


def task(module):
    value, details = science_prize_a.antichain_representations(module.construct(), **P)
    return runtime.success(value, 'minimize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
