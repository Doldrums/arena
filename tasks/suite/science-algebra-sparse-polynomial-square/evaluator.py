"""Sparse squares of twelve-term integer polynomials (Problem-bank constructions: arithmetic and extremal sets supplement).

Protocol: recreated_verified. Candidate contract: construct() -> candidate. Return coefficient list in ascending degree, length<=41, nonzero final coefficient, entries integers in [-64,64], exactly 12 nonzero terms. Minimize nonzero terms in the EXACT integer square..
Generated by scripts/build_suite.py from the family "science_prize_b_sparse_polynomial_square" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_b  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 60
P = {'terms': 12, 'degree': 40, 'coefficient_bound': 64}


def task(module):
    value, details = science_prize_b.sparse_polynomial_square(module.construct(), **P)
    return runtime.success(value, 'minimize', lean_verified=False, **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
