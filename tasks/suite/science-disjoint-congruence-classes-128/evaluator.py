"""Many disjoint residue classes with distinct moduli (Problem-bank constructions: additive combinatorics supplement).

Protocol: recreated_verified. Candidate contract: construct() -> a nonempty list of [residue,modulus] pairs with distinct moduli 2..maximum=128 and canonical residues 0<=r<m. Every two infinite residue classes must be disjoint; the verifier uses the exact gcd criterion. Maximize the number of classes..
Generated by scripts/build_suite.py from the family "science_prize_a_disjoint_congruences" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_a  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 60
P = {'maximum': 128}


def task(module):
    value, details = science_prize_a.disjoint_congruences(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
