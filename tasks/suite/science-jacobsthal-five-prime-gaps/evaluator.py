"""Long coprimality gaps for five-prime moduli (Problem-bank constructions: geometry and discrete structures supplement).

Protocol: recreated_verified. Candidate contract: construct() -> a squarefree integer n in [2,1000000] with exactly five distinct prime factors. Maximize the longest cyclic run of residues not coprime to n. This score equals j(n)-1, not j(n); every residue and the wraparound gap are checked..
Generated by scripts/build_suite.py from the family "science_prize_d_jacobsthal" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import science_prize_d  # noqa: E402

DIRECTION = "maximize"
TIMEOUT = 60
P = {'maximum': 1000000, 'prime_count': 5}


def task(module):
    value, details = science_prize_d.jacobsthal(module.construct(), **P)
    return runtime.success(value, 'maximize', **details)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
