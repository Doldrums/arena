"""Powell 4D (EvolCAF).

Protocol: recreated. Candidate contract: acquisition(mu, sigma, f_best, cost) -> one score per candidate point; the loop stops when accumulated cost exceeds the budget (EvolCAF-style; cost(x) = 1 + mean normalized coordinate, a documented stand-in for the paper's cost functions). Score: mean simple regret.
Generated by scripts/build_suite.py from the family "bo_cost_aware" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import blackbox  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 300
P = {'function': 'powell_4d', 'budget': 30}


def task(module):
    names = P.get('functions') or [P['function']]
    values = {name: blackbox.bo_regret_score(module.acquisition, name, budget=P['budget'], cost_model=True) for name in names}
    return runtime.success(sum(values.values()) / len(values), 'minimize', per_function=values)


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
