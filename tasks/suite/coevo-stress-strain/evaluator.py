"""Stress-strain (CoEvo, Deliberate Evolution, DrSR).

Protocol: recreated. Candidate contract: equation(<inputs>, params: np.ndarray[10]) -> np.ndarray prediction (LLM-SR contract); the ten parameters are fitted by BFGS on the training split. Score: NMSE on the in-distribution test split (OOD split also reported).
Generated by scripts/build_suite.py from the family "llmsr_equation" of the shared
suite library (suite/_lib/autoresearch_suite). Run:

    python evaluator.py initial_program.py
"""
from __future__ import annotations

import sys
from pathlib import Path

SUITE_LIB = Path(__file__).resolve().parents[1] / "_lib"
if str(SUITE_LIB) not in sys.path:
    sys.path.insert(0, str(SUITE_LIB))

from autoresearch_suite import runtime  # noqa: E402
from autoresearch_suite import regression  # noqa: E402

DIRECTION = "minimize"
TIMEOUT = 120
P = {'dataset': 'stress_strain'}


def task(module):
    out = regression.llmsr_score(module.equation, P['dataset'])
    return runtime.success(out['score'], 'minimize', nmse_test_ood=out['nmse_test_ood'], train_mse=out['train_mse'])


def evaluate(program_path="initial_program.py"):
    result = runtime.run(program_path, task, timeout=TIMEOUT)
    result["direction"] = DIRECTION
    return result


if __name__ == "__main__":
    sys.exit(runtime.main(evaluate))
