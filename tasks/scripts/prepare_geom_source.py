ROOT = Path(__file__).resolve().parents[1]
DATA = data_root() / 'materials-expansion/C02'
sys.path.insert(0, str(ROOT/'suite/_lib'))
from autoresearch_suite.science_materials_expansion import conformer_metrics
URL = 'https://zenodo.org/api/records/20633997/files/geom_qm9_data_v1.0_ntc_1000.hdf5.gz/content'
SOURCE_SHA256 = 'b16cf4c727fe57e6dfc6309815893d25d5524ba048b346ac5e2fbd2401c72e4c'
SOURCE_MD5 = '1627bf69a7029b2822733152f8a3e445'


def aligned_source_frames(smiles, atomic_numbers, coordinates_angstrom, charges):
    """Recover atom order only when every frame matches graph AND stereochemistry.

    Source SMILES are not atom-mapped and source atoms do not follow SMILES
    ordering. Independent geometry-based bond perception is used to verify an
    isomorphism; ambiguous/failed chemistry is excluded rather than guessed.
    """
    template = Chem.AddHs(Chem.MolFromSmiles(smiles))
    if len(atomic_numbers) != template.GetNumAtoms():
        raise ValueError('source atom count differs from explicit-H graph')
    aligned, mappings = [], []
    for frame, (positions, charge) in enumerate(zip(coordinates_angstrom, charges, strict=True)):
        if not np.isfinite(positions).all() or charge != int(charge):
            raise ValueError('invalid source coordinate/charge')
        inferred = Chem.RWMol()
        for z in atomic_numbers:
            inferred.AddAtom(Chem.Atom(int(z)))
        conformer = Chem.Conformer(len(atomic_numbers))
        for index, xyz in enumerate(positions):
            conformer.SetAtomPosition(index, xyz)
        inferred.AddConformer(conformer)
        try:
            rdDetermineBonds.DetermineBonds(inferred, charge=int(charge))
            matches = inferred.GetSubstructMatches(template, useChirality=True, uniquify=False, maxMatches=1)
            if not matches:
                raise ValueError('perceived graph/stereochemistry differs from source SMILES')
        except Exception as error:
            raise ValueError(f'frame{frame}: {error}') from None
        order = matches[0]
        if len(order) != len(atomic_numbers) or len(set(order)) != len(order):
            raise ValueError('atom mapping is not a bijection')
        if [int(atomic_numbers[i]) for i in order] != [atom.GetAtomicNum() for atom in template.GetAtoms()]:
            raise ValueError('atom identity changed during source mapping')
        aligned.append(positions[list(order)].tolist()); mappings.append(list(order))
    return aligned, mappings


def prepare():
    rawdir = DATA/'raw'; rawdir.mkdir(parents=True, exist_ok=True)
    compressed = rawdir/'geom_qm9_data_v1.0_ntc_1000.hdf5.gz'
    if not compressed.exists() or hashlib.sha256(compressed.read_bytes()).hexdigest() != SOURCE_SHA256:
        with urllib.request.urlopen(URL, timeout=90) as response:
            content = response.read()
        if hashlib.sha256(content).hexdigest() != SOURCE_SHA256:
            raise ValueError('published GEOM curation SHA256 changed')
        compressed.write_bytes(content)
    if hashlib.md5(compressed.read_bytes()).hexdigest() != SOURCE_MD5:
        raise ValueError('GEOM curation publisher MD5 mismatch')
    path = compressed.with_suffix(''); path.write_bytes(gzip.decompress(compressed.read_bytes()))
    cases, excluded, mapping_audit = [], [], {}
    with h5py.File(path) as file:
        if len(file) != 67 or sum(int(file[name]['n_configs'][()]) for name in file) != 1000:
            raise ValueError('published GEOM subset count changed')
        for name in sorted(file):
            molecule = file[name]
            smiles = molecule['smiles'][()].decode()
            if molecule['positions'].attrs.get('u') != 'nanometer':
                raise ValueError('unknown source coordinate unit')
            positions = molecule['positions'][:]*10  # nm -> Angstrom, exactly.
            atomic_numbers = molecule['atomic_numbers'][:].ravel().astype(int)
            charges = molecule['total_charge'][:].ravel()
            try:
                aligned, mappings = aligned_source_frames(smiles, atomic_numbers, positions, charges)
                # All reference frames must themselves meet the public molecular
                # identity/geometry contract before candidate evaluation.
                conformer_metrics(smiles, aligned, aligned[:1], maximum=len(aligned))
            except (ValueError, RuntimeError) as error:
                excluded.append({'source_group': name, 'conformers': len(positions), 'reason': str(error)})
                continue
            graph = Chem.MolFromSmiles(smiles)
            scaffold = MurckoScaffold.MurckoScaffoldSmiles(mol=graph, includeChirality=True) or 'acyclic'
            cases.append({'group_id': smiles, 'source_group': name, 'scaffold_group': scaffold,
                          'smiles': smiles, 'reference_coordinates': aligned, 'source_sha256': SOURCE_SHA256,
                          'atom_order_verified': 'all source frames reconstructed and chirality-preserving graph-isomorphic'})
            mapping_audit[name] = mappings
    # Whole ensembles pass or fail solely on source graph consistency, before
    # any candidate runs. No selection is based on baseline coverage/errors.
    provenance = {'source_url': 'https://zenodo.org/records/20633997', 'sha256': SOURCE_SHA256,
        'license': 'CC0-1.0, publisher metadata; original GEOM and ChoderaLab curation separately attributed',
        'source_file_url': URL, 'published_md5': SOURCE_MD5,
        'primary_GEOM': 'https://doi.org/10.7910/DVN/JNGTDF',
        'curation': 'ChoderaLab modelforge GEOM-QM9 nc_1000_v1.0, June10 2026; retained published coordinates, ignored energy fields',
        'selection': 'Every complete molecular ensemble whose every frame has a bijective element/graph/stereochemistry match to supplied source SMILES. Zero-shot evaluation of all retained ensembles; no fitted training split.',
        'adaptation': 'Secondary published GEOM-QM9 subset, not the entire original CREST ensemble archive or GEOM-Drugs. Coordinate nanometers converted to Angstrom. Excluded graph/valence/stereo-unresolved ensembles are documented; no new reference conformers generated.'}
    bundle = {'schema': 'sciel-materials-C02-v1', 'provenance': provenance, 'data_kind': 'computed_GEOM_QM9_via_Modelforge',
              'training': [], 'evaluation': cases}
    destination = DATA/'dataset.json'; destination.write_text(json.dumps(bundle)+'\n')
    (DATA/'source_mapping_audit.json').write_text(json.dumps({'source_sha256': SOURCE_SHA256, 'retained_atom_maps': mapping_audit, 'excluded_ensembles': excluded}, indent=2)+'\n')
    summary = {'proposal_id': 'C02', 'source_molecules': 67, 'source_conformers': 1000, 'retained_molecules': len(cases),
               'retained_conformers': sum(len(c['reference_coordinates']) for c in cases), 'excluded_ensembles': excluded,
               'dataset_sha256': hashlib.sha256(destination.read_bytes()).hexdigest(), 'source_sha256': SOURCE_SHA256}
    (DATA/'preparation.json').write_text(json.dumps(summary, indent=2)+'\n')
    return summary


if __name__=='__main__':
    print(json.dumps(prepare(), indent=2))
